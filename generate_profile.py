"""Emit the build-pinned code-capture profile from the saved audit."""
import json
from pathlib import Path


def generate(report):
    from .audit_exe import TARGET_SHA256
    if report["sha256"] != TARGET_SHA256:
        raise ValueError("Unexpected audit identity")
    names = ("UnitGUID", "UnitName", "CreateFrame", "SetUnit", "SetModel", "GetModelFileID", "SetCustomRace")
    lines = ["// Generated by python -m shadowlands.generate_profile; do not edit.",
             "#pragma once", "#include <cstdint>",
             "struct CodeRange { const char* name; uint32_t rva, size; unsigned char disk[16]; };",
             "inline constexpr CodeRange CodeRanges[] = {"]
    for name in names:
        for entry in report["anchors"][name]["candidates"]:
            raw = bytes.fromhex(entry["prefix_hex"])[:16]
            if len(raw) != 16 or not 0 < entry["function_end_rva"] - entry["function_rva"] <= 0x100000:
                raise ValueError("Invalid code range")
            lines.append('    {"%s", 0x%X, 0x%X, {%s}},' % (
                name, entry["function_rva"], entry["function_end_rva"] - entry["function_rva"],
                ", ".join("0x%02X" % value for value in raw)))
    return "\n".join(lines + ["};", ""])


if __name__ == "__main__":
    root = Path(__file__).resolve().parent
    (root / "ClientProfile.h").write_text(generate(json.loads((root / "exe-audit.json").read_text())), encoding="utf-8")

"""Generate the shared loader stub without embedding a client executable."""
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import patcher

def generate(source=None):
    stub = patcher.bootstrap(0, 0)
    return "// Generated by generate_patch_data.py.\n#pragma once\nnamespace PatchData {\ninline constexpr unsigned char Stub[] = {" + ",".join(f"0x{b:02x}" for b in stub) + "};\n}\n"

if __name__ == "__main__":
    Path(__file__).with_name("PatchData.h").write_text(generate(), encoding="ascii")

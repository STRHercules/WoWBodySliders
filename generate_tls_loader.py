"""Extract the relocation-free TLS shim from its MASM build."""
import base64
from pathlib import Path
import pefile


def generate(path):
    pe = pefile.PE(str(path))
    try:
        entry, = [s.address for s in pe.DIRECTORY_ENTRY_EXPORT.symbols if s.name == b"TlsLoader"]
        section = pe.get_section_by_rva(entry)
        if section.VirtualAddress != entry or getattr(pe, "DIRECTORY_ENTRY_IMPORT", None):
            raise ValueError("Unexpected shim layout or imports")
        for block in getattr(pe, "DIRECTORY_ENTRY_BASERELOC", ()):
            if any(entry <= r.rva < entry + section.Misc_VirtualSize and r.type for r in block.entries):
                raise ValueError("Shim has absolute code relocations")
        code = pe.get_data(entry, section.Misc_VirtualSize)
        return ('"""Generated by python -m shadowlands.generate_tls_loader."""\n'
                'import base64\n\nCODE = base64.b64decode(%r)\n' % base64.b64encode(code).decode("ascii"))
    finally:
        pe.close()


if __name__ == "__main__":
    root = Path(__file__).resolve().parent
    (root / "tls_loader_data.py").write_text(generate(root.parent / "build/shadowlands/Release/ShadowlandsTlsLoader.dll"), encoding="utf-8")
